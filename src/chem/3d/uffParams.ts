/** Default UFF label for elements that need no hybridisation-dependent typing. */
export function defaultLabelFor(el: string): string | null {
  for (const key of [el, el + '_', el + '3']) if (UFF_PARAMS.has(key)) return key;
  for (const key of UFF_PARAMS.keys()) {
    // e.g. 'Fe3+2', 'Ca6+2', 'Pt4+2': element symbol followed by a digit or '_'
    if (key.startsWith(el) && /^[0-9_]/.test(key.slice(el.length))) return key;
  }
  return null;
}

/** Generic parameters for elements (or pseudo atoms) missing from the table, derived from covalent radii. */
export function genericParams(el: string): UFFAtomParams {
  const e = element(el);
  const r = e?.covRadius && e.covRadius > 0 ? e.covRadius : 0.76;
  const dBlock = !!e && (e.group >= 3 && e.group <= 12 || e.group === 0);
  return {
    label: (e ? el : 'X') + '_g',
    r1: r,
    theta0: dBlock ? 90 : 109.47,
    x1: 1.8 * r + 2.2,
    D1: 0.05,
    zeta: 12,
    Z1: 2.0,
    Vi: 0,
    Uj: 0.1,
    Xi: e && e.en > 0 ? 2.1 * e.en : 4.0,
  };
}
